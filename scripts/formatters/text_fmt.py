# -*- coding: utf-8 -*-
"""Human-readable text report formatter."""

from scripts.utils.audio import format_time
from scripts.core.mood import get_mood_emoji
from scripts.core.vocal import get_vocal_summary


def format_text(analysis: dict) -> str:
    """Format analysis as a detailed human-readable text report."""
    lines = []
    
    name = analysis.get('filename', 'Unknown')
    duration = analysis.get('features', {}).get('duration_seconds', 0)
    
    lines.append("=" * 60)
    lines.append(f"🎵 E-Ears Full Analysis Report")
    lines.append(f"   File: {name}")
    lines.append(f"   Duration: {format_time(duration)}")
    lines.append("=" * 60)
    
    # Core Features
    features = analysis.get('features', {})
    lines.append(f"\n📊 CORE FEATURES")
    lines.append(f"   BPM: {features.get('bpm', 'N/A')}")
    lines.append(f"   Key: {features.get('key', 'N/A')} (confidence: {features.get('key_confidence', 0):.1%})")
    lines.append(f"   Time Signature: {features.get('time_signature', '4/4')}")
    lines.append(f"   Sample Rate: {features.get('sample_rate', 'N/A')} Hz")
    
    # Energy
    rms = features.get('rms_energy', {})
    lines.append(f"\n🔊 ENERGY")
    lines.append(f"   RMS Mean: {rms.get('mean', 0):.4f}")
    lines.append(f"   RMS Max: {rms.get('max', 0):.4f}")
    lines.append(f"   Dynamic Range: {rms.get('dynamic_range_db', 0):.1f} dB")
    
    # Spectral
    spectral = features.get('spectral', {})
    lines.append(f"\n📈 SPECTRAL")
    lines.append(f"   Centroid: {spectral.get('spectral_centroid', {}).get('mean', 0):.0f} Hz")
    lines.append(f"   Bandwidth: {spectral.get('spectral_bandwidth', {}).get('mean', 0):.0f} Hz")
    lines.append(f"   Rolloff: {spectral.get('spectral_rolloff', {}).get('mean', 0):.0f} Hz")
    lines.append(f"   ZCR: {spectral.get('zero_crossing_rate', {}).get('mean', 0):.5f}")
    
    # HNR
    hnr = features.get('hnr', {})
    lines.append(f"\n🎛️ HARMONICS")
    lines.append(f"   HNR: {hnr.get('hnr_db', 0):.1f} dB")
    lines.append(f"   Harmonic Ratio: {hnr.get('harmonic_ratio', 0):.3f}")
    
    # MFCC
    mfcc = features.get('mfcc', {})
    coeffs = mfcc.get('coefficients', [])
    if coeffs:
        lines.append(f"\n🎚️ MFCC ({len(coeffs)} coefficients)")
        lines.append(f"   {', '.join(f'{c:.1f}' for c in coeffs[:13])}")
    
    # Mood
    mood = analysis.get('mood', {})
    emoji = get_mood_emoji(mood.get('mood', 'Neutral'))
    lines.append(f"\n{emoji} MOOD")
    lines.append(f"   Mood: {mood.get('mood', 'N/A')}")
    lines.append(f"   Energy: {mood.get('energy', 0):.2f}/1.0")
    lines.append(f"   Danceability: {mood.get('danceability', 0):.2f}/1.0")
    lines.append(f"   Valence: {mood.get('valence', 0):.2f}/1.0")
    tags = mood.get('tags', [])
    if tags:
        lines.append(f"   Tags: {', '.join(tags)}")
    
    # Structure
    structure = analysis.get('structure', [])
    if structure:
        lines.append(f"\n🏗️ STRUCTURE ({len(structure)} sections)")
        for seg in structure:
            desc = f" — {seg['description']}" if seg.get('description') else ''
            lines.append(f"   {seg['start_fmt']}-{seg['end_fmt']} [{seg['label']}]{desc}")
    
    # Vocals
    vocal = analysis.get('vocal', {})
    lines.append(f"\n🎤 VOCALS")
    lines.append(f"   {get_vocal_summary(vocal)}")
    if vocal.get('has_vocals'):
        vr = vocal.get('vocal_range', {})
        lines.append(f"   Range: {vr.get('low', 'N/A')} - {vr.get('high', 'N/A')}")
        lines.append(f"   Register: {vocal.get('register', 'unknown')}")
        lines.append(f"   Gender: {vocal.get('gender_estimate', 'unknown')}")
    
    # Lyrics (if available)
    lyrics = analysis.get('lyrics', {})
    if lyrics and lyrics.get('text'):
        lines.append(f"\n📝 LYRICS (first 200 chars)")
        lines.append(f"   {lyrics['text'][:200]}...")
    
    lines.append("\n" + "=" * 60)
    lines.append("Generated by E-Ears 🦻")
    
    return '\n'.join(lines)
